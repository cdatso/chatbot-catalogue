-- 01-table-passages.sql
-- Cree les tables passages et questions, active le controle d'acces
-- (RLS), et la fonction de recherche plein texte.
-- Prototype d'apprentissage BKL-FOR-005 (a) -- executable tel quel dans
-- le SQL Editor de Supabase, PostgreSQL standard.
--
-- Rejouable : le drop en tete permet de repartir de zero apres un essai
-- rate (precedent FOR-003).

drop function if exists public.rechercher_passages(text, int);
drop table if exists public.passages;
drop table if exists public.questions;

create table public.passages (
    id bigint generated by default as identity primary key,
    slug text not null,
    titre text not null,
    realisateur text,
    annee int,
    url text not null,
    section text not null,
    ordre int not null,
    texte text not null,
    tsv tsvector generated always as (
        to_tsvector('french',
            coalesce(titre, '') || ' ' || coalesce(section, '') || ' ' || coalesce(texte, ''))
    ) stored
);

create index passages_tsv_idx on public.passages using gin (tsv);

-- Active le controle d'acces ligne par ligne : sans policy, personne ne
-- lit ni n'ecrit -- meme pas via la clef anon.
alter table public.passages enable row level security;

-- Seule policy : lecture publique (SELECT) pour le role anon (corpus
-- public, CC BY-NC-SA 4.0). Aucun INSERT, UPDATE ni DELETE public.
create policy "lecture publique passages"
    on public.passages
    for select
    to anon
    using (true);

-- Fonction de recherche plein texte, appelable par anon via PostgREST
-- (rpc). websearch_to_tsquery accepte une saisie en langage naturel.
create or replace function public.rechercher_passages(q text, k int default 6)
returns table (
    slug text,
    titre text,
    realisateur text,
    annee int,
    url text,
    section text,
    texte text,
    rang real
)
language sql
stable
as $$
    select
        p.slug,
        p.titre,
        p.realisateur,
        p.annee,
        p.url,
        p.section,
        p.texte,
        ts_rank(p.tsv, websearch_to_tsquery('french', q)) as rang
    from public.passages p
    where p.tsv @@ websearch_to_tsquery('french', q)
    order by rang desc
    limit k;
$$;

grant execute on function public.rechercher_passages(text, int) to anon;

-- Journal anonyme des questions posees au chatbot : zero IP, zero
-- identifiant. RLS activee, AUCUNE policy : l'ecriture se fait
-- uniquement depuis la Netlify Function, avec la cle service (jamais
-- via la cle anon publique).
create table public.questions (
    id bigint generated by default as identity primary key,
    at timestamptz not null default now(),
    question text not null,
    slugs text[] not null default '{}',
    refus boolean not null default false
);

alter table public.questions enable row level security;

